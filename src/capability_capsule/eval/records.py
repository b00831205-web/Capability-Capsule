"""Versioned records for training data and reproducible experiments."""

from datetime import datetime
from enum import StrEnum
from typing import Literal, Self

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    JsonValue,
    field_validator,
    model_validator,
)


class DatasetSplit(StrEnum):
    """Dataset partition assigned before model training."""

    TRAIN = "train"
    VALIDATION = "validation"
    TEST = "test"


class MessageRole(StrEnum):
    """Role of one message in a Teacher trajectory."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class StudyKind(StrEnum):
    """Whether an experiment is exploratory or confirmatory."""

    PILOT = "pilot"
    PRIMARY = "primary"


class RunStatus(StrEnum):
    """Terminal status of one evaluated task."""

    COMPLETED = "completed"
    FAILED = "failed"
    TIMED_OUT = "timed_out"
    POLICY_VIOLATION = "policy_violation"


class ToolCallRecord(BaseModel):
    """One structured tool request produced by the Teacher."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    name: str = Field(min_length=1)
    arguments: dict[str, JsonValue] = Field(default_factory=dict)

    @field_validator("name")
    @classmethod
    def reject_blank_name(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Tool name must not be blank")

        return value


class TrajectoryMessage(BaseModel):
    """One message stored in a Teacher-generated trajectory."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    role: MessageRole
    content: str = ""
    tool_calls: tuple[ToolCallRecord, ...] = ()
    tool_name: str | None = None

    @model_validator(mode="after")
    def validate_message_shape(self) -> Self:
        if not self.content.strip() and not self.tool_calls:
            raise ValueError("Message must contain text or a tool call")

        if self.tool_calls and self.role is not MessageRole.ASSISTANT:
            raise ValueError("Only assistant messages may request tools")

        if self.role is MessageRole.TOOL:
            if self.tool_name is None or not self.tool_name.strip():
                raise ValueError("Tool messages must identify their tool")
        elif self.tool_name is not None:
            raise ValueError("Only tool messages may set tool_name")

        return self


class TeacherTrajectory(BaseModel):
    """One auditable training trajectory generated by a Teacher model."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal["0.1"] = "0.1"
    trajectory_id: str = Field(min_length=1)
    task_id: str = Field(min_length=1)
    split: DatasetSplit
    teacher_model: str = Field(min_length=1)
    teacher_skill_version: str = Field(min_length=1)
    task: str = Field(min_length=1)
    messages: tuple[TrajectoryMessage, ...] = Field(min_length=2)
    source_revision: str | None = None
    tags: tuple[str, ...] = ()

    @field_validator(
        "trajectory_id",
        "task_id",
        "teacher_model",
        "teacher_skill_version",
        "task",
    )
    @classmethod
    def reject_blank_required_text(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Required text fields must not be blank")

        return value

    @field_validator("source_revision")
    @classmethod
    def reject_blank_revision(cls, value: str | None) -> str | None:
        if value is not None and not value.strip():
            raise ValueError("source_revision must not be blank")

        return value

    @field_validator("tags")
    @classmethod
    def reject_blank_tags(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        if any(not tag.strip() for tag in value):
            raise ValueError("Tags must not be blank")

        return value


class ExperimentManifest(BaseModel):
    """Pre-registered configuration shared by a set of experiment runs."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal["0.1"] = "0.1"
    experiment_id: str = Field(min_length=1)
    study_kind: StudyKind
    created_at: datetime
    candidate_models: tuple[str, ...] = Field(min_length=1)
    repetitions: int = Field(ge=1)
    cycle_task_count: int = Field(ge=1)
    memory_budget_mb: int = Field(ge=1)
    random_seed: int = Field(ge=0)
    held_out_dataset_id: str = Field(min_length=1)
    condition_ids: tuple[str, ...] = ()
    notes: str | None = None

    @field_validator("experiment_id", "held_out_dataset_id")
    @classmethod
    def reject_blank_identifiers(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Experiment identifiers must not be blank")

        return value

    @field_validator("candidate_models", "condition_ids")
    @classmethod
    def reject_blank_collection_values(
        cls,
        value: tuple[str, ...],
    ) -> tuple[str, ...]:
        if any(not item.strip() for item in value):
            raise ValueError("Collection values must not be blank")

        return value

    @field_validator("created_at")
    @classmethod
    def require_timezone(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("created_at must include a timezone")

        return value

    @model_validator(mode="after")
    def validate_repetition_count(self) -> Self:
        if self.study_kind is StudyKind.PRIMARY and self.repetitions < 30:
            raise ValueError(
                "Primary experiments require at least 30 repetitions"
            )

        return self


class CaseResult(BaseModel):
    """Immutable measurements from one evaluated task case."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal["0.1"] = "0.1"
    experiment_id: str = Field(min_length=1)
    run_id: str = Field(min_length=1)
    case_id: str = Field(min_length=1)
    model_id: str = Field(min_length=1)
    condition_id: str = Field(min_length=1)
    hardware_id: str = Field(min_length=1)
    repetition: int = Field(ge=1)
    cycle_position: int = Field(ge=1)
    status: RunStatus
    success: bool
    time_bounded_success: bool
    score: float | None = Field(default=None, ge=0.0, le=1.0)
    started_at: datetime
    duration_ms: float = Field(ge=0.0)
    input_tokens: int = Field(ge=0)
    output_tokens: int = Field(ge=0)
    peak_rss_mb: float = Field(ge=0.0)
    tool_call_count: int = Field(ge=0)
    invalid_tool_call_count: int = Field(ge=0)
    error_type: str | None = None

    @field_validator(
        "experiment_id",
        "run_id",
        "case_id",
        "model_id",
        "condition_id",
        "hardware_id",
    )
    @classmethod
    def reject_blank_identifiers(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("Result identifiers must not be blank")

        return value

    @field_validator("started_at")
    @classmethod
    def require_timezone(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("started_at must include a timezone")

        return value

    @field_validator("error_type")
    @classmethod
    def reject_blank_error_type(cls, value: str | None) -> str | None:
        if value is not None and not value.strip():
            raise ValueError("error_type must not be blank")

        return value

    @model_validator(mode="after")
    def validate_measurements(self) -> Self:
        if self.status is RunStatus.COMPLETED and self.score is None:
            raise ValueError("Completed results must include a score")

        if self.success and self.status is not RunStatus.COMPLETED:
            raise ValueError("Only completed results may be successful")

        if self.time_bounded_success and not self.success:
            raise ValueError(
                "Time-bounded success also requires task success"
            )

        if self.invalid_tool_call_count > self.tool_call_count:
            raise ValueError(
                "Invalid tool calls cannot exceed total tool calls"
            )

        return self